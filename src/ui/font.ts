export function glyphFor(char: string): number[] {
  return GLYPHS[char] ?? GLYPHS[char.toUpperCase()] ?? GLYPHS['?'];
}

/** Width in pixels of a string rendered at the given scale (1px letter gap). */
export function textWidth(text: string, scale: number, tracking = 1): number {
  if (text.length === 0) return 0;
  return text.length * (FONT_WIDTH + tracking) * scale - tracking * scale;
}

/** Greedy word wrap to a pixel width. */
export function wrapText(text: string, scale: number, maxWidth: number, tracking = 1): string[] {
  const words = text.split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let current = '';
  for (const word of words) {
    const candidate = current ? `${current} ${word}` : word;
    if (textWidth(candidate, scale, tracking) <= maxWidth || !current) current = candidate;
    else {
      lines.push(current);
      current = word;
    }
  }
  if (current) lines.push(current);
  return lines;
}
