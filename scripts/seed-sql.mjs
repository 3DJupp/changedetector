// Turns seed/sites.json into seed/sites.sql for `wrangler d1 execute`.
//
// Unlike POST /admin/seed this does not consult robots.txt up front. The
// crawler checks robots.txt before every fetch, so a disallowed page is simply
// never captured.
import { readFileSync, writeFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { canonicalizeUrl } from '../src/lib/urlguard.ts';
import { CATEGORIES as CATEGORY_LIST } from '../src/types.ts';

const root = new URL('..', import.meta.url);
const entries = JSON.parse(readFileSync(new URL('seed/sites.json', root), 'utf8'));
const CATEGORIES = new Set(CATEGORY_LIST);
const INTERVAL = { HIGH: 1800, NORMAL: 21600, LOW: 86400 };

const q = (value) => (value == null ? 'NULL' : `'${String(value).replace(/'/g, "''")}'`);
const now = Math.floor(Date.now() / 1000);

const lines = ['-- Generated by scripts/seed-sql.mjs from seed/sites.json. Do not edit.'];
for (const entry of entries) {
  const canonical = canonicalizeUrl(entry.url);
  const host = new URL(canonical).host;
  const priority = INTERVAL[entry.priority] ? entry.priority : 'NORMAL';
  const category = CATEGORIES.has(entry.category) ? entry.category : 'Companies';
  const id = `site_${randomBytes(12).toString('hex')}`;
  lines.push(
    `INSERT OR IGNORE INTO monitored_sites (id, url, canonical_url, host, title, category, status, crawl_interval_s, priority, render_mode, robots_allowed, next_check_at, created_at, updated_at) VALUES (${[
      q(id), q(entry.url), q(canonical), q(host), q(entry.title ?? null), q(category), q('ACTIVE'),
      INTERVAL[priority], q(priority), q('AUTO'), 1, now, now, now,
    ].join(', ')});`,
  );
}
writeFileSync(new URL('seed/sites.sql', root), lines.join('\n') + '\n');
console.log(`seed/sites.sql: ${entries.length} sites`);
